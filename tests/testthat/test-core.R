testthat::test_that("features are backward-looking and retain all 29 inputs", {
  x <- generate_trace(500)
  f <- extract_features(x)
  testthat::expect_equal(ncol(f), 29L)
  testthat::expect_true(all(is.finite(as.matrix(f))))
  testthat::expect_equal(f[1:100, ], extract_features(x[1:100, ]))
  testthat::expect_equal(f$rtt_slope_5m[6], (x$rtt_ms[6] - x$rtt_ms[1]) / 5)
  testthat::expect_equal(f$rtt_std_5m[1], 0)
  testthat::expect_equal(f$queue_mean_5m[5], mean(x$queue_occupancy_pct[1:5]))
  testthat::expect_equal(f$rtt_ewma[2], .2 * x$rtt_ms[2] + .8 * x$rtt_ms[1])
})
testthat::test_that("future targets do not wrap and temporal folds are purged", {
  x <- generate_trace(1000)
  y <- future_targets(x, 30)
  testthat::expect_equal(y$rtt[1], x$rtt_ms[31])
  testthat::expect_true(all(is.na(tail(y$rtt, 30))))
  split <- temporal_split(nrow(x))
  testthat::expect_lt(max(split$train) + 30, min(split$calibration))
  testthat::expect_lt(max(split$calibration) + 30, min(split$test))
  testthat::expect_lte(max(split$test) + 30, nrow(x))
})
testthat::test_that("buffers isolate interfaces, bound memory and reject batches atomically", {
  x <- generate_trace(800); windows <- new_windows()
  ingest_records(windows, x)
  testthat::expect_equal(nrow(window_history(windows)), 720L)
  other <- x[1:40, ]; other$device_id <- "router-two"
  ingest_records(windows, other)
  testthat::expect_equal(nrow(window_history(windows, "router-two")), 40L)
  testthat::expect_error(ingest_records(windows, tail(x, 1)), "increase")
  bad <- tail(x, 2); bad$timestamp <- bad$timestamp + 120; bad$packet_loss_pct[2] <- -1
  testthat::expect_error(ingest_records(windows, bad), "Invalid")
  testthat::expect_equal(tail(window_history(windows)$timestamp, 1), tail(x$timestamp, 1))
  testthat::expect_error(window_history(windows, "unknown"), "No telemetry")
  testthat::expect_error(window_history(windows, limit = -1), "limit")
  testthat::expect_error(latest_features(x[1:10, ]), "30")
  x$timestamp[40] <- x$timestamp[40] + 1
  testthat::expect_error(latest_features(x[1:40, ]), "one-minute")
})
testthat::test_that("isotonic regression handles ties, constants and monotonicity", {
  fit <- fit_isotonic(c(.1, .1, .2, .3, .4), c(0, 1, 0, 1, 1))
  testthat::expect_true(all(diff(fit$y) >= 0))
  testthat::expect_equal(fit$y[1], 1 / 3)
  testthat::expect_equal(calibrate_prob(fit_isotonic(rep(.2, 3), c(0, 0, 1)), c(0, 1)), rep(1 / 3, 2))
  testthat::expect_equal(conformal_quantile(1:9, rep(0, 9)), 9)
})
