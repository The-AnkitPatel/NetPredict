testthat::test_that("models, replay, explanations and scenarios work together", {
  withr::local_dir("../..")
  trace <- load_trace()
  system <- train_system(trace, trees = 20)
  service <- new_service(system, trace)
  baseline <- predict_latest(service)
  testthat::expect_equal(length(baseline$horizons), 3L)
  for (h in baseline$horizons) {
    testthat::expect_gte(h$calibrated_probability, 0)
    testthat::expect_lte(h$calibrated_probability, 1)
    testthat::expect_lte(h$conformal_lower_bound_rtt, h$predicted_rtt_ms)
    testthat::expect_gte(h$conformal_upper_bound_rtt, h$predicted_rtt_ms)
  }
  testthat::expect_equal(nrow(window_history(service$windows)), 45L)
  predict_latest(service)
  testthat::expect_equal(nrow(window_history(service$windows)), 45L)
  testthat::expect_error(predict_latest(service, "unknown"), "No telemetry")
  jump <- step_stream(service, "jump-incident")
  testthat::expect_gt(jump$record$queue_occupancy_pct, 85)
  features <- latest_features(window_history(service$windows))
  explanation <- explain_features(system, features, permutations = 6)
  testthat::expect_equal(explanation$base_value + sum(vapply(explanation$all_attributions, function(a) a$shap_value, numeric(1))), explanation$predicted_risk, tolerance = 1e-10)
  original <- window_history(service$windows)
  no_op <- simulate_scenario(service, list())
  testthat::expect_equal(no_op$baseline_risk, no_op$counterfactual_risk)
  testthat::expect_equal(no_op$baseline_rtt_ms, no_op$counterfactual_rtt_ms)
  simulation <- simulate_scenario(service, list(reroute_traffic_pct = 40, enable_priority_queuing = TRUE))
  testthat::expect_lt(simulation$counterfactual_queue_pct, simulation$baseline_queue_pct)
  testthat::expect_identical(window_history(service$windows), original)
  testthat::expect_error(simulate_scenario(service, list(reroute_traffic_pct = 101)), "Invalid")
  testthat::expect_error(simulate_scenario(service, list(horizon_minutes = 7)), "Unsupported")
  testthat::expect_error(simulate_scenario(service, list(enable_priority_queuing = "yes")), "boolean")
  file <- tempfile(fileext = ".rds")
  on.exit(unlink(file), add = TRUE)
  save_system(system, file)
  restored <- load_system(file, trace)
  testthat::expect_equal(predict_horizon(restored, features), predict_horizon(system, features))
  testthat::expect_equal(anomaly_score(restored, tail(original, 1)), anomaly_score(system, tail(original, 1)))
  step_stream(service, "reset")
  testthat::expect_equal(service$cursor, 46L)
  testthat::expect_equal(nrow(window_history(service$windows)), 46L)
  testthat::expect_equal(length(service$incidents), 0L)
  testthat::expect_equal(recalibrate_system(service)$status, "RECALIBRATED")
  testthat::expect_true(all(is.finite(unlist(system$health$evaluation_metrics))))
})
