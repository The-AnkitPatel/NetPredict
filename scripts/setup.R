dir.create(".R-library", showWarnings = FALSE)
.libPaths(c(normalizePath(".R-library"), .Library))
packages <- c("plumber", "jsonlite", "ranger", "isotree", "testthat", "rmarkdown", "knitr", "callr", "curl", "httpuv", "withr")
db <- available.packages(repos = "https://cloud.r-project.org")
dependencies <- unique(c(packages, unlist(tools::package_dependencies(packages, db = db, recursive = TRUE))))
missing <- setdiff(dependencies, rownames(installed.packages()))
if (length(missing)) install.packages(missing, lib = ".R-library", repos = "https://cloud.r-project.org")
cat("Dependencies ready. Run Rscript scripts/run_api.R\n")
